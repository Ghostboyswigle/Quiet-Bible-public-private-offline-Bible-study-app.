const SORTED = [...BOOK_ALIASES].sort((a, b) => b[0].length - a[0].length);

export function resolveBookAlias(raw: string): string | null {
  const key = raw
    .toLowerCase()
    .replace(/\./g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!key) return null;
  for (const [alias, id] of SORTED) {
    if (key === alias) return id;
  }
  return null;
}
